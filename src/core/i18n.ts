export const UI_STRINGS: Record<Language, Record<UiKey, string>> = { fr, en };

export type Translate = (key: UiKey, params?: Record<string, string | number>) => string;

export function createTranslator(lang: Language): Translate {
  const dict = UI_STRINGS[lang];
  return (key, params) => {
    let s = dict[key] ?? UI_STRINGS.fr[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export function formatMoney(value: number, lang: Language): string {
  return `$${value.toLocaleString(lang === 'fr' ? 'fr-FR' : 'en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export function formatDate(date: string, lang: Language, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long' }): string {
  const d = new Date(`${date}T00:00:00Z`);
  return d.toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-GB', { timeZone: 'UTC', ...opts });
}
